/**
 * `keystone proof` — the machine- and human-readable result proof (PRD DP-01..03).
 *
 * The proof is a deterministic projection of the ledger, not a summary written
 * by a model, so re-exporting it cannot change the verdict. Exports never carry
 * credentials: the proof package references a model by id and a credential by
 * handle only, so a redacted export is simply a proof with file content removed.
 */

import { mkdir, stat, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

import type { Translator } from "@keystone/i18n";
import { KernelSession } from "@keystone/kernel";
import type { ProofPackage } from "@keystone/schemas";

import { getBoolean, parseArgs, requireString, UsageError } from "../args.ts";
import { createOutput, type Output } from "../output.ts";
import {
  gitChangedPaths,
  pathsFor,
  readWorkspaceRoot,
  toTaskId,
  translatorForContext,
  type CliContext,
  type CommandModule,
} from "./shared.ts";

/**
 * Determine what changed, using git as the ground truth. `undefined` from git is
 * reported honestly rather than being flattened into "nothing changed".
 */
async function detectChangedPaths(
  context: CliContext,
  session: KernelSession,
  output: Output,
  t: Translator,
): Promise<string[]> {
  const root = await readWorkspaceRoot(pathsFor(context), session.projectId);
  if (root === undefined) {
    output.error(
      t("The task's workspace root is unknown; the proof is exported with an empty change set."),
    );
    return [];
  }
  const detected = await gitChangedPaths(root);
  if (detected === undefined) {
    output.error(t("git status could not be read; the proof is exported with an empty change set."));
    return [];
  }
  if (detected.length === 0) output.line(t("No changes detected in the workspace."));
  return detected;
}

async function openSession(context: CliContext, taskIdValue: string): Promise<KernelSession> {
  return KernelSession.open({ paths: pathsFor(context), taskId: toTaskId(taskIdValue) });
}

function printProof(proof: ProofPackage, output: Output, t: Translator): void {
  output.section(t("Proof"));
  output.keyValue({
    [t("packageId")]: proof.packageId,
    [t("taskId")]: proof.taskId,
    [t("outcome")]: proof.outcome,
    [t("goal")]: proof.goal,
    [t("changed files")]: proof.changes.changedFileCount,
    [t("within scope")]: proof.changes.withinScope ? "yes" : "no",
  });
  // The summary is prose generated by the kernel: a stable, hash-addressed part
  // of the artifact, so it is shown verbatim and never re-worded here.
  output.line(proof.summary);

  output.section(t("Completion conditions"));
  if (proof.conditions.length === 0) output.line(`  ${t("(no conditions were evaluated)")}`);
  for (const condition of proof.conditions) {
    const achieved =
      condition.achievedLevel === undefined
        ? ""
        : `, ${t("achieved {level}", { level: condition.achievedLevel })}`;
    output.line(
      `  ${t("[{status}] {id} ({kind}, min {min}{achieved}) — {reason}", {
        status: condition.satisfied ? "ok  " : "OPEN",
        id: condition.conditionId,
        kind: condition.required ? t("required") : t("auxiliary"),
        min: condition.requiredLevel,
        achieved,
        reason: condition.reasonCode,
      })}`,
    );
  }

  output.section(t("Evidence index"));
  if (proof.evidenceIndex.length === 0) output.line(`  ${t("none")}`);
  for (const entry of proof.evidenceIndex) {
    output.line(
      `  ${entry.level} ${entry.status} ${entry.producerId}@${entry.producerVersion} ` +
        `(${entry.independenceMode}) → ${entry.conditionIds.join(", ")}`,
    );
    output.detail(t("evidenceId: {id}", { id: entry.evidenceId }));
  }

  output.section(t("Not verified and residual risk"));
  if (proof.unverified.length === 0 && proof.residualRisks.length === 0) {
    output.line(`  ${t("none reported")}`);
  }
  for (const item of proof.unverified) output.line(`  ${t("unverified: {item}", { item })}`);
  for (const item of proof.residualRisks) output.line(`  ${t("residual risk: {item}", { item })}`);

  output.section(t("Reproduce"));
  for (const command of proof.reproduceCommands) output.line(`  ${command}`);
  output.detail(t("proof graph hash: {hash}", { hash: proof.proofGraphHash }));
}

async function runShow(argv: readonly string[], context: CliContext): Promise<number> {
  const args = parseArgs(argv, {
    positionals: ["taskId"],
    flags: { json: "boolean", verbose: "boolean" },
  });
  const output = createOutput({
    stdout: context.stdout,
    stderr: context.stderr,
    json: getBoolean(args, "json"),
    verbose: getBoolean(args, "verbose"),
  });
  const t = translatorForContext(context);
  const taskIdValue = args.positionals[0];
  if (taskIdValue === undefined) return 2;

  const session = await openSession(context, taskIdValue);
  const changedPaths = await detectChangedPaths(context, session, output, t);
  const proof = await session.exportProof({ changedPaths });

  printProof(proof, output, t);
  output.json(proof);
  return 0;
}

async function runExport(argv: readonly string[], context: CliContext): Promise<number> {
  const args = parseArgs(argv, {
    positionals: ["taskId"],
    flags: { out: "string", redacted: "boolean", json: "boolean", verbose: "boolean" },
  });
  const output = createOutput({
    stdout: context.stdout,
    stderr: context.stderr,
    json: getBoolean(args, "json"),
    verbose: getBoolean(args, "verbose"),
  });
  const t = translatorForContext(context);
  const taskIdValue = args.positionals[0];
  if (taskIdValue === undefined) return 2;
  const outFile = requireString(args, "out");
  const redacted = getBoolean(args, "redacted");

  const session = await openSession(context, taskIdValue);
  const changedPaths = await detectChangedPaths(context, session, output, t);
  const proof = await session.exportProof({
    changedPaths,
    redaction: redacted ? "metadata_only" : "none",
  });

  // 0600: a proof may reference paths and hashes the user has not published yet.
  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, `${JSON.stringify(proof, null, 2)}\n`, { mode: 0o600 });
  const { size } = await stat(outFile);

  output.line(
    t("Wrote the proof for task {taskId} to {outFile} ({size} bytes, redaction={redaction}).", {
      taskId: taskIdValue,
      outFile,
      size,
      redaction: proof.redaction,
    }),
  );
  output.detail(t("proof graph hash: {hash}", { hash: proof.proofGraphHash }));
  output.json({ out: outFile, bytes: size, redaction: proof.redaction, proofGraphHash: proof.proofGraphHash });
  return 0;
}

async function run(argv: readonly string[], context: CliContext): Promise<number> {
  const sub = argv[0];
  const rest = argv.slice(1);
  switch (sub) {
    case "show":
      return runShow(rest, context);
    case "export":
      return runExport(rest, context);
    default:
      throw new UsageError(
        `unknown subcommand "proof ${sub ?? ""}"; expected "proof show" or "proof export"`,
      );
  }
}

export const command: CommandModule = {
  name: "proof",
  summary: (t) => t("Show or export the machine-readable result proof"),
  usage: "keystone proof <show|export> <taskId> [options]",
  help: [
    "keystone proof show <taskId> [--json] [--verbose]",
    "  Print the proof: summary, per-condition status, evidence, unverified items,",
    "  residual risks and reproduction commands.",
    "",
    "keystone proof export <taskId> --out <file> [--redacted]",
    "  Write the structured proof to a file. --redacted keeps only metadata",
    "  (summaries, hashes, statuses, references) and strips file content.",
    "  Exports never contain credentials.",
  ].join("\n"),
  run,
};
