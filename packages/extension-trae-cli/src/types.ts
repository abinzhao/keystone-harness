export interface TransportParameters {
  readonly command: string;
  readonly args: readonly string[];
  readonly cwd: string;
  readonly temporaryRoot: string;
  readonly stdinHash: string;
  readonly stdinBytes: number;
  readonly environmentHash: string;
  readonly outputSchemaHash?: string;
  readonly cliDigest: string;
  readonly sourceExecutable: string;
  readonly purpose: "version" | "help" | "models" | "generate";
  readonly timeoutMs: number;
  readonly maxOutputBytes: number;
  readonly maxNetworkBytes: number;
  readonly egressHosts: readonly string[];
  readonly nativeAuthFile?: string;
  readonly nativeModelsFile?: string;
  readonly allowPrivateNetwork?: boolean;
}
export interface TransportProposal {
  readonly subject: { readonly kind: "extension"; readonly id: string };
  readonly capability: "cmd.exec";
  readonly resource: { readonly kind: "command"; readonly values: readonly string[]; readonly mode: "execute" };
  readonly parameters: TransportParameters;
  readonly parametersHash: string;
}
// Structural boundary until the composition root supplies the authoritative
// schemas. The callback is trusted runtime code, never a model/tool result.
export interface TransportLease {
  readonly leaseId: string;
  readonly taskId: string;
  readonly branchId: string;
  readonly subject: { readonly kind: string; readonly id: string };
  readonly capability: string;
  readonly resource: { readonly kind: string; readonly values: readonly string[]; readonly mode?: string };
  readonly constraints: {
    readonly workingDirectory?: string;
    readonly timeoutMs?: number;
    readonly maxOutputBytes?: number;
    readonly argvPrefix?: readonly string[];
    readonly parametersHash?: string;
  };
  readonly budget: { readonly maxCalls: number; readonly maxBytes?: number; readonly maxWallClockMs?: number };
  readonly scopeDigest: string;
  readonly issuedAt: string;
  readonly expiresAt: string;
  readonly issuedBy: string;
  readonly status: string;
  readonly consumedCalls: number;
}
export type AuthorizeTransport = (proposal: TransportProposal) => Promise<TransportLease>;
export interface TransportPolicy {
  readonly extensionSubject: string;
  readonly executable: string;
  readonly argvPrefix: readonly string[];
}
export interface TransportLimits {
  readonly timeoutMs?: number;
  readonly maxInputBytes?: number;
  readonly maxOutputBytes?: number;
  readonly maxFrameBytes?: number;
  readonly maxNetworkBytes?: number;
}
export interface TraeCliOptions {
  readonly cliPath: string;
  readonly endpointHost: string;
  readonly egressHosts: readonly string[];
  readonly extensionSubject?: string;
  readonly limits?: TransportLimits;
  readonly isActive?: () => boolean | Promise<boolean>;
  readonly checkIntegrity?: () => boolean | Promise<boolean>;
  readonly onIsolationViolation?: (reason: "isolation_violation") => void;
  /** CLI-owned file, read by CLI in place. The transport never reads its bytes. */
  readonly nativeAuthFile?: string;
  /** CLI-owned model metadata, read in place; never parsed by the transport. */
  readonly nativeModelsFile?: string;
  readonly allowPrivateNetwork?: boolean;
  /** Generated by the host's authoritative validator, never model-authored. */
  readonly outputSchema?: Readonly<Record<string, unknown>>;
}
export interface ProbeOptions {
  readonly authorizeTransport: AuthorizeTransport;
  readonly signal?: AbortSignal;
}
export interface TraeCliModelOptions extends TraeCliOptions, ProbeOptions {
  readonly modelName: string;
  readonly id?: string;
}
export interface TraeCliRequest {
  readonly messages: readonly {
    readonly role: "system" | "user" | "assistant";
    readonly content: string | readonly ({ readonly type: string; readonly text?: string })[];
  }[];
  readonly tools: readonly unknown[];
  readonly jsonMode: boolean;
  readonly maxTokens?: number;
  readonly temperature?: number;
  readonly signal?: AbortSignal;
  readonly authorizeTransport?: AuthorizeTransport;
}
export interface TraeCliResponse {
  readonly text: string;
  readonly toolCalls: readonly [];
  readonly usage: { readonly inputTokens: number; readonly outputTokens: number };
  readonly measuredUsage: {
    readonly inputTokens: number; readonly outputTokens: number; readonly cachedInputTokens?: number;
  };
  readonly modelName: string;
  readonly finishReason: string;
}
export interface CompatibilityResult {
  readonly compatible: true;
  readonly version: "0.210.1";
  readonly platform: "darwin";
  readonly cliPath: string;
  readonly cliDigest: string;
  readonly confinement: "macos-seatbelt-connect-sni";
  readonly structuredOutput: true;
  readonly nativeTools: false;
  readonly authentication: "not-verified";
  readonly transportPolicy: TransportPolicy;
  readonly egressHosts: readonly string[];
}
